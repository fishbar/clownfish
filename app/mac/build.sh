#!/usr/bin/env bash
# Assemble Clownfish.app — a self-contained bundle:
#
#   Contents/MacOS/clownfish-mac      the Rust shell (window + webview)
#   Contents/MacOS/clownfish-server   the server, compiled by bun (--compile)
#   Contents/MacOS/clownfish-worker   the agent worker, ditto
#   Contents/Resources/web-dist/      the Vite build of the web UI
#
# No node/npm needed at RUNTIME: bun embeds its runtime in the binaries, and
# the worker is spawned as a binary (CLOWNFISH_WORKER_BIN), not forked as a
# module. Build-time prerequisites: bun, cargo, and `npm install` at the repo
# root (the web build + bun's module resolution use node_modules).
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd ../.. && pwd)"

APP="Clownfish.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

echo "» web UI (vite)"
(cd "$ROOT" && npm run build >/dev/null)

echo "» server + worker (bun --compile)"
bun build "$ROOT/server/index.ts" --compile --outfile "$APP/Contents/MacOS/clownfish-server"
bun build "$ROOT/agent/worker.ts" --compile --outfile "$APP/Contents/MacOS/clownfish-worker"

echo "» shell (cargo)"
cargo build --release
cp target/release/clownfish-mac "$APP/Contents/MacOS/"
cp Info.plist "$APP/Contents/"

cp -R "$ROOT/dist" "$APP/Contents/Resources/web-dist"

# Icon: generated by `node scripts/logo-assets.mjs` at the repo root. Optional.
if [ -f "$ROOT/assets/logo.icns" ]; then
	cp "$ROOT/assets/logo.icns" "$APP/Contents/Resources/"
	/usr/libexec/PlistBuddy -c "Set :CFBundleIconFile logo" "$APP/Contents/Info.plist"
fi

echo "built $APP"
echo "run:   open ./$APP    (or: ./$APP/Contents/MacOS/clownfish-mac)"
